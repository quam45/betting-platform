-- 001 Initial Schema - BettingPlatformDb
-- Use DECIMAL(19,4) for money, UTC, rowversion, append-only ledger

CREATE TABLE Users (
    UserId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    Email NVARCHAR(320) NOT NULL UNIQUE,
    PasswordHash NVARCHAR(512) NOT NULL,
    Status NVARCHAR(20) NOT NULL CHECK (Status IN ('Active','Suspended','Closed')),
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    RowVersion ROWVERSION
);

CREATE TABLE Wallets (
    WalletId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    UserId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Users(UserId),
    CurrencyCode CHAR(3) NOT NULL DEFAULT 'NGN',
    Status NVARCHAR(20) NOT NULL DEFAULT 'Active',
    RowVersion ROWVERSION,
    UNIQUE(UserId, CurrencyCode)
);

CREATE TABLE WalletLedgerEntries (
    LedgerEntryId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    WalletId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Wallets(WalletId),
    EntryType NVARCHAR(50) NOT NULL,
    Amount DECIMAL(19,4) NOT NULL,
    ReferenceType NVARCHAR(50) NOT NULL,
    ReferenceId UNIQUEIDENTIFIER NOT NULL,
    IdempotencyKey NVARCHAR(100) NOT NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UNIQUE(WalletId, IdempotencyKey)
);

CREATE TABLE Sports (
    SportId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    Name NVARCHAR(100) NOT NULL UNIQUE,
    IsActive BIT NOT NULL DEFAULT 1
);

CREATE TABLE Competitions (
    CompetitionId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    SportId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Sports(SportId),
    Name NVARCHAR(200) NOT NULL,
    Country NVARCHAR(100),
    IsActive BIT NOT NULL DEFAULT 1
);

CREATE TABLE Events (
    EventId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    CompetitionId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Competitions(CompetitionId),
    HomeTeam NVARCHAR(200) NOT NULL,
    AwayTeam NVARCHAR(200) NOT NULL,
    StartTimeUtc DATETIME2 NOT NULL,
    Status NVARCHAR(20) NOT NULL CHECK (Status IN ('Open','Suspended','Closed','Settled')),
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    RowVersion ROWVERSION
);

CREATE TABLE Markets (
    MarketId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    EventId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Events(EventId),
    Name NVARCHAR(200) NOT NULL,
    Status NVARCHAR(20) NOT NULL DEFAULT 'Open',
    SettlementStatus NVARCHAR(20) NOT NULL DEFAULT 'Pending'
);

CREATE TABLE Selections (
    SelectionId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    MarketId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Markets(MarketId),
    Name NVARCHAR(200) NOT NULL,
    OutcomeCode NVARCHAR(20) NOT NULL,
    CurrentOdds DECIMAL(19,4) NOT NULL CHECK (CurrentOdds >= 1.01 AND CurrentOdds <= 1000),
    Status NVARCHAR(20) NOT NULL DEFAULT 'Open',
    RowVersion ROWVERSION
);

CREATE TABLE OddsHistory (
    OddsHistoryId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    SelectionId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Selections(SelectionId),
    DecimalOdds DECIMAL(19,4) NOT NULL,
    EffectiveAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    ChangedByUserId UNIQUEIDENTIFIER NULL
);

CREATE TABLE Bets (
    BetId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    UserId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Users(UserId),
    BetType NVARCHAR(20) NOT NULL DEFAULT 'Single',
    Stake DECIMAL(19,4) NOT NULL CHECK (Stake > 0),
    PotentialReturn DECIMAL(19,4) NOT NULL,
    Status NVARCHAR(20) NOT NULL DEFAULT 'Pending',
    IdempotencyKey NVARCHAR(100) NOT NULL,
    IdempotencyHash NVARCHAR(100) NOT NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UNIQUE(UserId, IdempotencyKey)
);

CREATE TABLE BetSelections (
    BetSelectionId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    BetId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Bets(BetId),
    SelectionId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Selections(SelectionId),
    EventId UNIQUEIDENTIFIER NOT NULL,
    MarketId UNIQUEIDENTIFIER NOT NULL,
    OddsAtPlacement DECIMAL(19,4) NOT NULL
);

CREATE TABLE EventResults (
    ResultId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    EventId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Events(EventId),
    WinningSelectionId UNIQUEIDENTIFIER NOT NULL,
    ResultPayload NVARCHAR(MAX) NULL,
    VerifiedBy UNIQUEIDENTIFIER NOT NULL,
    VerifiedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE SettlementRecords (
    SettlementId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    BetId UNIQUEIDENTIFIER NOT NULL FOREIGN KEY REFERENCES Bets(BetId),
    Outcome NVARCHAR(20) NOT NULL,
    StakeReturned DECIMAL(19,4) NOT NULL DEFAULT 0,
    PayoutAmount DECIMAL(19,4) NOT NULL DEFAULT 0,
    SettledAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UniqueSettlementKey NVARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE AuditLogs (
    AuditLogId UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(),
    ActorUserId UNIQUEIDENTIFIER NOT NULL,
    Action NVARCHAR(100) NOT NULL,
    EntityType NVARCHAR(100) NOT NULL,
    EntityId NVARCHAR(200) NOT NULL,
    CorrelationId NVARCHAR(100) NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    SafeMetadata NVARCHAR(MAX) NULL
);